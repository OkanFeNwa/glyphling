PITCH = 120          # distanza tra i punti, in unità (em = 1000)
RADIUS = 54          # raggio del punto
ADV = PITCH * 6      # glifo .notdef: 5 colonne + 1 di spazio
BASE = 0             # la riga 6 poggia sulla linea di base


def circle(pen, cx, cy, r):
    # cerchio con 8 curve quadratiche
    import math
    pts = []
    for i in range(8):
        a = i * math.pi / 4
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    pen.moveTo((round(pts[0][0]), round(pts[0][1])))
    for i in range(8):
        a0 = i * math.pi / 4
        p1 = pts[(i + 1) % 8]
        # punto di controllo all'incrocio delle tangenti
        c = (cx + r / math.cos(math.pi / 8) * math.cos(a0 + math.pi / 8), cy + r / math.cos(math.pi / 8) * math.sin(a0 + math.pi / 8))
        pen.qCurveTo((round(c[0]), round(c[1])), (round(p1[0]), round(p1[1])))
    pen.closePath()


def build(out_dir):
    names = {c: ('space' if c == ' ' else f'uni{ord(c):04X}') for c in G}
    order = ['.notdef'] + [names[c] for c in G]
    glyphs, metrics = {}, {}
    pen = TTGlyphPen(None)
    pen.moveTo((60, 0)); pen.lineTo((60, 840)); pen.lineTo((600, 840)); pen.lineTo((600, 0)); pen.closePath()
    glyphs['.notdef'] = pen.glyph(); metrics['.notdef'] = (ADV, 60)
    for c, rows in G.items():
        pen = TTGlyphPen(None)
        assert all(len(row) == 5 for row in rows), c
        used = [col for col in range(5) if any(row[col] == '#' for row in rows)]
        # proporzionale come il font di Nothing: si tolgono le colonne vuote ai lati,
        # tranne che per le cifre, che restano larghe uguali per non far ballare l'ora
        if c.isdigit() or not used:
            first, cols = 0, (5 if used else 3)
        else:
            first, cols = used[0], used[-1] - used[0] + 1
        for r, row in enumerate(rows):
            for col, ch in enumerate(row):
                if ch == '#':
                    circle(pen, PITCH // 2 + (col - first) * PITCH, BASE + (6 - r) * PITCH + PITCH // 2, RADIUS)
        glyphs[names[c]] = pen.glyph()
        metrics[names[c]] = ((cols + 1) * PITCH, PITCH // 2 - RADIUS if used else 0)

    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({ord(c): names[c] for c in G})
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=900, descent=-240)
    fb.setupNameTable({
        'familyName': 'Glyphling Dot', 'styleName': 'Regular',
        'copyright': 'Glyphling Dot, font a punti di Glyphling. SIL Open Font License 1.1.',
        'version': 'Version 1.000', 'uniqueFontIdentifier': 'GlyphlingDot-Regular',
    })
    fb.setupOS2(sTypoAscender=900, sTypoDescender=-240, sTypoLineGap=0, usWinAscent=900, usWinDescent=240,
                sxHeight=600, sCapHeight=840, fsType=0, achVendID='GLPH')
    fb.setupPost()
    fb.font['head'].flags |= 1 << 3
    fb.font.flavor = 'woff2'
    fb.font.save(f'{out_dir}/GlyphlingDot.woff2')
    print(f'{len(G)} glifi in {out_dir}')


if __name__ == '__main__':
    build(sys.argv[1] if len(sys.argv) > 1 else 'src/fonts')
